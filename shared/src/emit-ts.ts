// Emits one Zod module per schema file into shared/ts/.
// Zod 4 API: https://zod.dev/api

import {
  deref,
  discriminator,
  nullableInner,
  parseRef,
  topoOrder,
  type JsonSchema,
  type SchemaFile,
} from "./schema.js";

const HEADER = `// Generated by shared/src/generate.ts from shared/schemas/. Do not edit.
// Regenerate with: pnpm --filter @nkata/shared generate
`;

function tsString(s: string): string {
  return JSON.stringify(s);
}

export function emitTs(files: Map<string, SchemaFile>, file: SchemaFile): string {
  const imports = new Map<string, Set<string>>();

  const refExpr = (ref: string): string => {
    const r = parseRef(ref, file.base);
    if (r.base !== file.base) {
      const set = imports.get(r.base) ?? new Set<string>();
      set.add(r.name);
      imports.set(r.base, set);
    }
    return r.name;
  };

  const expr = (node: JsonSchema): string => {
    if (node.$ref !== undefined) return refExpr(node.$ref);
    const inner = nullableInner(node);
    if (inner) return `${expr(inner)}.nullable()`;
    const branches = node.oneOf ?? node.anyOf;
    if (branches) {
      const disc = discriminator(files, branches, file.base);
      const members = branches.map(expr).join(", ");
      return disc ? `z.discriminatedUnion(${tsString(disc)}, [${members}])` : `z.union([${members}])`;
    }
    if (node.const !== undefined) return `z.literal(${JSON.stringify(node.const)})`;
    if (node.enum) return `z.enum([${node.enum.map((v) => JSON.stringify(v)).join(", ")}])`;
    switch (node.type) {
      case "string": {
        let e = "z.string()";
        if (node.format === "date-time") e = "z.iso.datetime({ offset: true })";
        if (node.format === "email") e = "z.email()";
        if (node.format === "uri") e = "z.url()";
        if (node.minLength !== undefined) e += `.min(${node.minLength})`;
        if (node.pattern !== undefined) e += `.regex(new RegExp(${tsString(node.pattern)}))`;
        return e;
      }
      case "integer":
      case "number": {
        let e = node.type === "integer" ? "z.number().int()" : "z.number()";
        if (node.minimum !== undefined) e += `.min(${node.minimum})`;
        if (node.maximum !== undefined) e += `.max(${node.maximum})`;
        return e;
      }
      case "boolean":
        return "z.boolean()";
      case "null":
        return "z.null()";
      case "array": {
        let e = `z.array(${node.items ? expr(node.items) : "z.unknown()"})`;
        if (node.minItems !== undefined) e += `.min(${node.minItems})`;
        if (node.maxItems !== undefined) e += `.max(${node.maxItems})`;
        return e;
      }
      case "object": {
        const props = node.properties ?? {};
        const required = new Set(node.required ?? []);
        if (Object.keys(props).length === 0) {
          if (node.additionalProperties === false) return "z.strictObject({})";
          const valueExpr = typeof node.additionalProperties === "object" ? expr(node.additionalProperties) : "z.unknown()";
          return `z.record(z.string(), ${valueExpr})`;
        }
        const fields = Object.entries(props)
          .map(([key, prop]) => `  ${tsString(key)}: ${expr(prop)}${required.has(key) ? "" : ".optional()"},`)
          .join("\n");
        const ctor = node.additionalProperties === false ? "z.strictObject" : "z.looseObject";
        return `${ctor}({\n${fields}\n})`;
      }
      default:
        throw new Error(`unsupported schema node in ${file.base}: ${JSON.stringify(node)}`);
    }
  };

  const body: string[] = [];
  for (const name of topoOrder(file)) {
    const def = file.defs[name];
    if (!def) continue;
    const resolved = deref(files, def, file.base).node;
    const doc = resolved.description ?? def.description;
    if (doc) body.push(`/** ${doc} */`);
    body.push(`export const ${name} = ${expr(def)};`);
    body.push(`export type ${name} = z.infer<typeof ${name}>;`);
    body.push("");
  }

  const importLines = ['import { z } from "zod";'];
  for (const [base, names] of [...imports.entries()].sort()) {
    importLines.push(`import { ${[...names].sort().join(", ")} } from "./${base}.js";`);
  }
  return `${HEADER}\n${importLines.join("\n")}\n\n${body.join("\n")}`;
}

export function emitTsIndex(files: Map<string, SchemaFile>): string {
  const lines = [...files.keys()].sort().map((base) => `export * from "./${base}.js";`);
  return `${HEADER}\n${lines.join("\n")}\n`;
}
