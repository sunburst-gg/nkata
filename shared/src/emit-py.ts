// Emits one Python module per schema file into shared/py/.
// Each $def becomes a frozen dataclass, a Literal alias, or a Union alias,
// plus a validate_<Name>(value) function that checks a decoded JSON value and
// builds the typed object. shared/py/_runtime.py holds the primitive checks.

import {
  deref,
  discriminator,
  nullableInner,
  parseRef,
  type JsonSchema,
  type SchemaFile,
} from "./schema.js";

const HEADER = `# Generated by shared/src/generate.ts from shared/schemas/. Do not edit.
# Regenerate with: pnpm --filter @nkata/shared generate
`;

const PY_KEYWORDS = new Set([
  "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
  "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
  "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
]);

/** JSON key to Python attribute. Keywords get a trailing underscore; the JSON key is kept in field metadata. */
export function pyFieldName(key: string): string {
  return PY_KEYWORDS.has(key) ? `${key}_` : key;
}

function pyString(s: string): string {
  return JSON.stringify(s);
}

function pyLiteralValue(v: string | number | boolean | null): string {
  if (v === null) return "None";
  if (typeof v === "boolean") return v ? "True" : "False";
  if (typeof v === "string") return pyString(v);
  return String(v);
}

export function emitPy(files: Map<string, SchemaFile>, file: SchemaFile): string {
  const imports = new Map<string, Set<string>>();
  const classes: string[] = [];
  const aliases: string[] = [];
  const validators: string[] = [];

  const refName = (ref: string): string => {
    const r = parseRef(ref, file.base);
    if (r.base !== file.base) {
      const set = imports.get(r.base) ?? new Set<string>();
      set.add(r.name);
      set.add(`validate_${r.name}`);
      imports.set(r.base, set);
    }
    return r.name;
  };

  // Python type expression for a node. Inline objects get a generated class.
  const typeExpr = (node: JsonSchema, nameHint: string): string => {
    if (node.$ref !== undefined) return refName(node.$ref);
    const inner = nullableInner(node);
    if (inner) return `${typeExpr(inner, nameHint)} | None`;
    const branches = node.oneOf ?? node.anyOf;
    if (branches) {
      const disc = discriminator(files, branches, file.base);
      return branches
        .map((b, i) => {
          const d = deref(files, b, file.base).node;
          const suffix = disc && d.properties?.[disc]?.const !== undefined ? String(d.properties[disc]?.const) : String(i);
          return typeExpr(b, `${nameHint}_${suffix}`);
        })
        .join(" | ");
    }
    if (node.const !== undefined) return `Literal[${pyLiteralValue(node.const)}]`;
    if (node.enum) return `Literal[${node.enum.map((v) => pyLiteralValue(v)).join(", ")}]`;
    switch (node.type) {
      case "string":
        return "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "null":
        return "None";
      case "array":
        return `list[${node.items ? typeExpr(node.items, `${nameHint}_item`) : "Any"}]`;
      case "object": {
        const props = node.properties ?? {};
        if (Object.keys(props).length === 0) return "dict[str, Any]";
        emitClass(nameHint, node);
        return nameHint;
      }
      default:
        throw new Error(`unsupported schema node in ${file.base}: ${JSON.stringify(node)}`);
    }
  };

  const emitted = new Set<string>();
  const emitClass = (name: string, node: JsonSchema): void => {
    if (emitted.has(name)) return;
    emitted.add(name);
    const props = node.properties ?? {};
    const required = new Set(node.required ?? []);
    const fields: string[] = [];
    // Dataclass rule: fields without defaults come first. Optional fields default to None.
    const ordered = [...Object.entries(props)].sort(([a], [b]) => Number(!required.has(a)) - Number(!required.has(b)));
    for (const [key, prop] of ordered) {
      const attr = pyFieldName(key);
      const t = typeExpr(prop, `${name}_${key}`);
      const meta: string[] = [];
      if (attr !== key) meta.push(`"json_key": ${pyString(key)}`);
      if (!required.has(key)) meta.push('"optional": True');
      const metaExpr = meta.length ? `metadata={${meta.join(", ")}}` : "";
      if (required.has(key)) {
        fields.push(`    ${attr}: ${t}${metaExpr ? ` = field(${metaExpr})` : ""}`);
      } else {
        fields.push(`    ${attr}: ${t} | None = field(default=None${metaExpr ? `, ${metaExpr}` : ""})`);
      }
    }
    const doc = node.description ? `    """${node.description}"""\n` : "";
    const loose = node.additionalProperties !== false;
    classes.push(
      `@dataclass(frozen=True)\nclass ${name}:\n${doc}${fields.join("\n")}\n\n    def to_dict(self) -> dict[str, Any]:\n        return _rt.to_dict(self)\n`,
    );
    validators.push(emitObjectValidator(name, node, loose));
  };

  // Validator expression: returns the name of a function (value, path) -> typed.
  const validatorFn = (node: JsonSchema, nameHint: string): string => {
    if (node.$ref !== undefined) return `validate_${refName(node.$ref)}`;
    const inner = nullableInner(node);
    if (inner) {
      const fn = `_v_${nameHint}`;
      const innerFn = validatorFn(inner, `${nameHint}_inner`);
      validators.push(`def ${fn}(value: object, path: str) -> Any:\n    if value is None:\n        return None\n    return ${innerFn}(value, path)\n`);
      return fn;
    }
    const branches = node.oneOf ?? node.anyOf;
    if (branches) {
      const fn = `_v_${nameHint}`;
      const disc = discriminator(files, branches, file.base);
      if (disc) {
        const cases = branches.map((b, i) => {
          const d = deref(files, b, file.base).node;
          const value = d.properties?.[disc]?.const;
          const suffix = value !== undefined ? String(value) : String(i);
          return `        ${pyLiteralValue(value as string)}: ${validatorFn(b, `${nameHint}_${suffix}`)},`;
        });
        validators.push(
          `def ${fn}(value: object, path: str) -> Any:\n    return _rt.check_discriminated(value, path, ${pyString(disc)}, {\n${cases.join("\n")}\n    })\n`,
        );
      } else {
        const fns = branches.map((b, i) => validatorFn(b, `${nameHint}_${i}`));
        validators.push(`def ${fn}(value: object, path: str) -> Any:\n    return _rt.check_any_of(value, path, [${fns.join(", ")}])\n`);
      }
      return fn;
    }
    const fn = `_v_${nameHint}`;
    if (node.const !== undefined) {
      validators.push(`def ${fn}(value: object, path: str) -> Any:\n    return _rt.check_literal(value, path, (${pyLiteralValue(node.const)},))\n`);
      return fn;
    }
    if (node.enum) {
      validators.push(`def ${fn}(value: object, path: str) -> Any:\n    return _rt.check_literal(value, path, (${node.enum.map(pyLiteralValue).join(", ")},))\n`);
      return fn;
    }
    switch (node.type) {
      case "string": {
        const args = [
          `min_length=${node.minLength ?? 0}`,
          `pattern=${node.pattern !== undefined ? pyString(node.pattern) : "None"}`,
          `fmt=${node.format !== undefined ? pyString(node.format) : "None"}`,
        ];
        validators.push(`def ${fn}(value: object, path: str) -> str:\n    return _rt.check_str(value, path, ${args.join(", ")})\n`);
        return fn;
      }
      case "integer":
      case "number": {
        const check = node.type === "integer" ? "check_int" : "check_float";
        const args = [`minimum=${node.minimum ?? "None"}`, `maximum=${node.maximum ?? "None"}`];
        validators.push(`def ${fn}(value: object, path: str) -> ${node.type === "integer" ? "int" : "float"}:\n    return _rt.${check}(value, path, ${args.join(", ")})\n`);
        return fn;
      }
      case "boolean":
        validators.push(`def ${fn}(value: object, path: str) -> bool:\n    return _rt.check_bool(value, path)\n`);
        return fn;
      case "null":
        validators.push(`def ${fn}(value: object, path: str) -> None:\n    return _rt.check_null(value, path)\n`);
        return fn;
      case "array": {
        const itemFn = node.items ? validatorFn(node.items, `${nameHint}_item`) : "_rt.check_any";
        validators.push(
          `def ${fn}(value: object, path: str) -> list[Any]:\n    return _rt.check_list(value, path, ${itemFn}, min_items=${node.minItems ?? "None"}, max_items=${node.maxItems ?? "None"})\n`,
        );
        return fn;
      }
      case "object": {
        const props = node.properties ?? {};
        if (Object.keys(props).length === 0) {
          const valueFn = typeof node.additionalProperties === "object" ? validatorFn(node.additionalProperties, `${nameHint}_value`) : "_rt.check_any";
          validators.push(`def ${fn}(value: object, path: str) -> dict[str, Any]:\n    return _rt.check_dict(value, path, ${valueFn})\n`);
          return fn;
        }
        emitClass(nameHint, node);
        return `validate_${nameHint}`;
      }
      default:
        throw new Error(`unsupported schema node in ${file.base}: ${JSON.stringify(node)}`);
    }
  };

  const emitObjectValidator = (name: string, node: JsonSchema, loose: boolean): string => {
    const props = node.properties ?? {};
    const required = node.required ?? [];
    const lines = [`def validate_${name}(value: object, path: str = "$") -> ${name}:`];
    lines.push(
      `    obj = _rt.check_object(value, path, required=(${required.map(pyString).join(", ")}${required.length ? "," : ""}), allowed=${loose ? "None" : `(${Object.keys(props).map(pyString).join(", ")}${Object.keys(props).length ? "," : ""})`})`,
    );
    const args: string[] = [];
    for (const [key, prop] of Object.entries(props)) {
      const attr = pyFieldName(key);
      const fn = validatorFn(prop, `${name}_${key}`);
      if (required.includes(key)) {
        args.push(`        ${attr}=${fn}(obj[${pyString(key)}], path + ${pyString(`.${key}`)}),`);
      } else {
        args.push(`        ${attr}=${fn}(obj[${pyString(key)}], path + ${pyString(`.${key}`)}) if ${pyString(key)} in obj else None,`);
      }
    }
    lines.push(`    return ${name}(\n${args.join("\n")}\n    )\n`);
    return lines.join("\n");
  };

  for (const [name, def] of Object.entries(file.defs)) {
    const resolved = deref(files, def, file.base).node;
    if (def.$ref === undefined && resolved.type === "object" && Object.keys(resolved.properties ?? {}).length > 0) {
      emitClass(name, def);
    } else {
      const t = typeExpr(def, name);
      const doc = def.description ? `# ${def.description}\n` : "";
      aliases.push(`${doc}${name} = ${t}\n`);
      const fn = validatorFn(def, name);
      validators.push(`def validate_${name}(value: object, path: str = "$") -> Any:\n    return ${fn}(value, path)\n`);
    }
  }
  const importLines = [
    "from __future__ import annotations",
    "",
    "from dataclasses import dataclass, field",
    "from typing import Any, Literal",
    "",
    "from . import _runtime as _rt",
  ];
  for (const [base, names] of [...imports.entries()].sort()) {
    importLines.push(`from .${base} import ${[...names].sort().join(", ")}`);
  }
  // Keep every imported name referenced so linters stay quiet on re-exports.
  const used = [...imports.values()].flatMap((s) => [...s]).sort();
  const usedLine = used.length ? `\n__imported__ = (${used.join(", ")},)\n` : "";

  // Classes first: a union alias names the classes it joins.
  return `${HEADER}${importLines.join("\n")}\n${usedLine}\n${classes.join("\n")}\n${aliases.join("\n")}\n${validators.join("\n")}`;
}

export function emitPyInit(files: Map<string, SchemaFile>): string {
  const lines = [...files.keys()].sort().map((base) => `from .${base} import *  # noqa: F401,F403`);
  return `${HEADER}from ._runtime import ValidationError, to_dict  # noqa: F401\n${lines.join("\n")}\n`;
}

export const PY_RUNTIME = `# Runtime for the generated Python modules. Hand written, not generated.
# Primitive checks shared by every validate_<Name> function.
from __future__ import annotations

import dataclasses
import re
from datetime import datetime
from typing import Any, Callable


class ValidationError(ValueError):
    """Raised when a decoded JSON value does not match its schema. path points at the field."""

    def __init__(self, path: str, message: str) -> None:
        super().__init__(f"{path}: {message}")
        self.path = path
        self.message = message


Validator = Callable[[object, str], Any]

_EMAIL = re.compile(r"^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$")
_URI = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.-]*:")


def check_any(value: object, path: str) -> Any:
    return value


def check_null(value: object, path: str) -> None:
    if value is not None:
        raise ValidationError(path, "expected null")
    return None


def check_bool(value: object, path: str) -> bool:
    if not isinstance(value, bool):
        raise ValidationError(path, "expected boolean")
    return value


def check_int(value: object, path: str, minimum: int | None, maximum: int | None) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        if isinstance(value, float) and value.is_integer():
            value = int(value)
        else:
            raise ValidationError(path, "expected integer")
    if minimum is not None and value < minimum:
        raise ValidationError(path, f"expected >= {minimum}")
    if maximum is not None and value > maximum:
        raise ValidationError(path, f"expected <= {maximum}")
    return value


def check_float(value: object, path: str, minimum: float | None, maximum: float | None) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValidationError(path, "expected number")
    if minimum is not None and value < minimum:
        raise ValidationError(path, f"expected >= {minimum}")
    if maximum is not None and value > maximum:
        raise ValidationError(path, f"expected <= {maximum}")
    return value


def check_str(value: object, path: str, min_length: int, pattern: str | None, fmt: str | None) -> str:
    if not isinstance(value, str):
        raise ValidationError(path, "expected string")
    if len(value) < min_length:
        raise ValidationError(path, f"expected at least {min_length} characters")
    if pattern is not None and re.search(pattern, value) is None:
        raise ValidationError(path, f"does not match {pattern}")
    if fmt == "date-time":
        try:
            datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError as e:
            raise ValidationError(path, "expected ISO 8601 date-time") from e
    elif fmt == "email" and _EMAIL.match(value) is None:
        raise ValidationError(path, "expected email")
    elif fmt == "uri" and _URI.match(value) is None:
        raise ValidationError(path, "expected uri")
    return value


def check_literal(value: object, path: str, allowed: tuple[Any, ...]) -> Any:
    for a in allowed:
        if type(a) is type(value) and a == value:
            return value
    raise ValidationError(path, f"expected one of {list(allowed)}")


def check_list(value: object, path: str, item: Validator, min_items: int | None, max_items: int | None) -> list[Any]:
    if not isinstance(value, list):
        raise ValidationError(path, "expected array")
    if min_items is not None and len(value) < min_items:
        raise ValidationError(path, f"expected at least {min_items} items")
    if max_items is not None and len(value) > max_items:
        raise ValidationError(path, f"expected at most {max_items} items")
    return [item(v, f"{path}[{i}]") for i, v in enumerate(value)]


def check_dict(value: object, path: str, item: Validator) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValidationError(path, "expected object")
    return {k: item(v, f"{path}.{k}") for k, v in value.items()}


def check_object(value: object, path: str, required: tuple[str, ...], allowed: tuple[str, ...] | None) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValidationError(path, "expected object")
    for key in required:
        if key not in value:
            raise ValidationError(f"{path}.{key}", "required")
    if allowed is not None:
        extra = [k for k in value if k not in allowed]
        if extra:
            raise ValidationError(f"{path}.{extra[0]}", "unknown property")
    return value


def check_any_of(value: object, path: str, validators: list[Validator]) -> Any:
    errors: list[str] = []
    for v in validators:
        try:
            return v(value, path)
        except ValidationError as e:
            errors.append(str(e))
    raise ValidationError(path, "no branch matched: " + "; ".join(errors))


def check_discriminated(value: object, path: str, key: str, branches: dict[Any, Validator]) -> Any:
    if not isinstance(value, dict):
        raise ValidationError(path, "expected object")
    tag = value.get(key)
    branch = branches.get(tag)
    if branch is None:
        raise ValidationError(f"{path}.{key}", f"expected one of {list(branches)}")
    return branch(value, path)


def to_dict(value: Any) -> Any:
    """Dataclass to plain JSON value. Optional fields set to None are left out."""
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        out: dict[str, Any] = {}
        for f in dataclasses.fields(value):
            v = getattr(value, f.name)
            if f.metadata.get("optional") and v is None:
                continue
            out[f.metadata.get("json_key", f.name)] = to_dict(v)
        return out
    if isinstance(value, list):
        return [to_dict(v) for v in value]
    if isinstance(value, dict):
        return {k: to_dict(v) for k, v in value.items()}
    return value
`;
