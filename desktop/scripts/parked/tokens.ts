// Generates src/styles/tokens.ts from the machine-readable tokens.json in the handoff.
// Run: pnpm tokens. The output is committed; the test suite fails if it drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../src/styles/tokens/tokens.json", import.meta.url));
const out = fileURLToPath(new URL("../src/styles/tokens.ts", import.meta.url));

export function generateTokens(json: string): string {
  const t = JSON.parse(json) as Record<string, unknown>;
  const literal = JSON.stringify(t, null, 2);
  return `// Generated by scripts/tokens.ts from src/styles/tokens/tokens.json. Do not edit.
// Regenerate with: pnpm tokens
export const tokens = ${literal} as const;

export type Tokens = typeof tokens;
export type StateName = keyof typeof tokens.color.state;
export type NeutralStep = keyof typeof tokens.color.neutral.dark;

/** CSS variable name for a state color, for use in style props. */
export function stateVar(state: Exclude<StateName, "onState">): string {
  const name = state === "syncFailed" ? "sync-failed" : state;
  return \`var(--state-\${name})\`;
}
`;
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  writeFileSync(out, generateTokens(readFileSync(src, "utf8")));
  process.stdout.write(`${out}\n`);
}
